        <h1>Política de tratamiento de datos personales – SIGIP</h1>
        <p>Sistema de Información para la Gestión Integral del Gimnasio Universitario, Bienestar Universitario,
            Institución Universitaria Pascual Bravo.</p>

        <h2>1. Marco legal</h2>
        <p>Esta política aplica la Ley Estatutaria 1581 de 2012 de protección de datos personales y su
            reglamentación (Decreto 1377 de 2013, compilado en el Decreto Único 1074 de 2015).</p>

        <h2>2. Responsable del tratamiento</h2>
        <p>Institución Universitaria Pascual Bravo, a través de la dependencia de Bienestar Universitario,
            que administra el gimnasio universitario.</p>

        <h2>3. Datos que se recogen</h2>
        <ul>
            <li>Identificación: nombre, apellido, tipo y número de documento, género y fecha de nacimiento.</li>
            <li>Contacto: correo electrónico y teléfono.</li>
            <li>Vinculación: rol en la institución (estudiante, docente, administrativo, egresado, etc.).</li>
            <li>Salud: EPS a la que pertenece. Es un <strong>dato sensible</strong>; su entrega es opcional.</li>
            <li>Uso del gimnasio: planes, pagos, ingresos, préstamos de implementos, reservas y actividades.</li>
        </ul>

        <h2>4. Finalidades</h2>
        <ul>
            <li>Registrar y controlar el acceso al gimnasio y verificar que el plan esté vigente.</li>
            <li>Gestionar suscripciones, pagos, préstamos, reservas de espacios y actividades.</li>
            <li>Actuar en caso de una emergencia o lesión dentro del gimnasio (EPS).</li>
            <li>Elaborar reportes estadísticos de uso para Bienestar Universitario.</li>
            <li>Enviar avisos relacionados con el servicio.</li>
        </ul>

        <h2>5. Derechos del titular</h2>
        <p>Como titular de los datos usted puede:</p>
        <ul>
            <li>Conocer, actualizar y rectificar sus datos personales.</li>
            <li>Pedir prueba de la autorización que otorgó.</li>
            <li>Ser informado sobre el uso que se les ha dado.</li>
            <li>Revocar la autorización o pedir que se eliminen, cuando no exista un deber legal o contractual de conservarlos.</li>
            <li>Presentar quejas ante la Superintendencia de Industria y Comercio.</li>
            <li>Acceder gratuitamente a sus datos.</li>
        </ul>

        <h2>6. Cómo ejercer sus derechos</h2>
        <p>Las consultas y reclamos se presentan ante Bienestar Universitario por sus canales oficiales.
            Las consultas se responden en máximo 10 días hábiles y los reclamos en máximo 15 días hábiles,
            según los artículos 14 y 15 de la Ley 1581 de 2012.</p>

        <h2>7. Seguridad de la información</h2>
        <p>SIGIP protege los datos con acceso por usuario y contraseña, permisos por tipo de cuenta,
            verificación en dos pasos para administradores, contraseñas cifradas y un registro de auditoría
            que no se puede modificar. Solo el personal autorizado consulta la información.</p>

        <h2>8. Autorización</h2>
        <p>Al registrarse en el gimnasio, el usuario autoriza el tratamiento de sus datos para las finalidades
            descritas. SIGIP guarda la fecha y hora de esa autorización.</p>

